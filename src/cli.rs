//! Аргументы командной строки. Флаги простые, без значений — кроме --session X.

/// Разобранные аргументы: что показать и как вести себя при запуске.
#[derive(Clone, Debug)]
pub struct Options {
    /// -h / --help: только справка
    pub help: bool,
    /// --once: один снимок в консоль и выход
    pub once: bool,
    /// --bell: звонок, когда сессия перестала быть занятой
    pub bell: bool,
    /// нет --no-ask: просить план у сессий самому
    pub auto_ask: bool,
    /// --session X: сразу открыть сессию (часть имени или id)
    pub session: Option<String>,
    /// --plan: открыть сразу весь план выбранной сессии
    pub plan: bool,
    /// --tips: открыть сразу советы
    pub tips: bool,
    /// --skills: открыть сразу историю скиллов
    pub skills: bool,
}

/// Разбирает аргументы без имени программы.
pub fn parse(args: &[String]) -> Options {
    let has = |f: &str| args.iter().any(|a| a == f);
    // значение флага — следующий аргумент; если флага нет или он последний, значения нет
    let val = |f: &str| args.iter().position(|a| a == f).and_then(|i| args.get(i + 1)).cloned();
    Options {
        help: has("-h") || has("--help"),
        once: has("--once"),
        bell: has("--bell"),
        auto_ask: !has("--no-ask"),
        session: val("--session"),
        plan: has("--plan"),
        tips: has("--tips"),
        skills: has("--skills"),
    }
}

